"""Generate four distinct 2-bit 240x240 vein maps for ARTIHIVE pastel themes."""
from pathlib import Path
import math, random
W=H=240
SPECS = {
    "VIOLET_VEIN_TEX": (0xA87121, 0.30, [24, 82, 145, 205], [23,31,19,29]),
    "LIME_VEIN_TEX":   (0xA87132,-0.22, [36, 104, 174],    [27,20,34]),
    "CREAM_VEIN_TEX":  (0xA87143, 0.12, [18, 67, 128, 191],[34,25,30,22]),
    "PEARL_VEIN_TEX":  (0xA87265, 0.17, [12, 52, 91, 132, 174, 218], [18,27,20,31,23,17]),
}

def make(seed, slope, bases, periods):
    rng=random.Random(seed)
    harmonics=[(rng.uniform(.018,.07),rng.uniform(.015,.062),rng.uniform(0,6.28),rng.uniform(1.2,4.5)) for _ in range(8)]
    vals=[]
    for y in range(H):
        for x in range(W):
            curves=[]
            for j,(base,period) in enumerate(zip(bases,periods)):
                direction=slope if j%2==0 else -slope*.72
                curves.append(base+direction*x+(8+j*1.7)*math.sin(x/period+j*1.13))
            d=min(abs(y-c) for c in curves)
            d += sum(math.sin(x*fx+y*fy+ph)*amp for fx,fy,ph,amp in harmonics)
            # Each seed changes the crossing hairline field as well.
            phase=(seed&255)/17
            hair=abs((x*(.19+(seed&7)*.025)+y*(.48+((seed>>4)&7)*.035)+7*math.sin((x+y)/31+phase))%83-41.5)
            if seed == 0xA87265:
                hair2=abs((x*.71-y*.29+9*math.sin(x/17+1.4))%57-28.5)
                lv=3 if d<1.7 else 2 if d<4.9 or hair<.48 else 1 if d<10.8 or hair<1.05 or hair2<.62 else 0
            else:
                lv=3 if d<1.55 else 2 if d<4.4 else 1 if d<8.8 or hair<.55 else 0
            vals.append(lv)
    out=bytearray((len(vals)+3)//4)
    for i,v in enumerate(vals): out[i>>2]|=v<<((i&3)*2)
    return out

lines=['/* generated by tools/gen_pastel_textures.py; four independent 2-bit 240x240 maps */']
for name,args in SPECS.items():
    data=make(*args); lines.append(f'static const uint8_t {name}[14400] = {{')
    for i in range(0,len(data),24): lines.append('    '+', '.join(f'0x{x:02x}' for x in data[i:i+24])+',')
    lines.append('};')
Path('firmware/gen/pastel_textures.h').write_text('\n'.join(lines)+'\n')
