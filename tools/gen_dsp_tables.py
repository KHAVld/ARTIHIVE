"""Generate the integer-only DSP tables. Float arithmetic stays on the build computer.

    python3 tools/gen_dsp_tables.py          # rewrite firmware/gen/artihive_tables.h
    python3 tools/gen_dsp_tables.py --check  # CI: the checked-in header is current

REL is inverted, as on the panel: 0 is the longest tail, 127 the shortest.
Times are full-scale release to -60 dB at 44100 Hz. FAST keeps the old short
range; SLOW keeps the old 93 ms endpoint and extends the other end to 8 s.
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "firmware" / "gen" / "artihive_tables.h"
FS = 44100


def release(lo, hi):
    return [max(1, round((1 - math.exp(-math.log(1000) / (lo * (hi / lo) ** (i / 127) * FS))) * (1 << 24)))
            for i in range(128)]


def release_ms(lo, hi):
    return [round(lo * (hi / lo) ** (i / 127) * 1000) for i in range(128)]


def attack_ms():
    # a_atk = 1 + (127-atk)^2/48 counts per sample at 44100 Hz, full scale 32767
    return [round(32767 * 1000 / ((1 + (127 - a) * (127 - a) // 48) * 44100)) for a in range(128)]


def rows(name, values, typ):
    s = f"static const {typ} {name}[128] = {{\n"
    for i in range(0, 128, 8):
        s += "    " + ", ".join(f"{v}u" for v in values[i:i + 8]) + ",\n"
    return s + "};\n"


def make():
    s = ("/* Generated by tools/gen_dsp_tables.py; do not edit. SPDX-License-Identifier: GPL-3.0-only */\n"
         "#pragma once\n#include <stdint.h>\n\n"
         "/* Q24 one-minus-decay per sample; REL 0..127 is inverted.\n"
         " * FAST 54..2.4 ms, SLOW 8000..93 ms, full scale to -60 dB at 44100 Hz. */\n")
    s += rows("REL_FAST", release(0.054, 0.0024), "uint32_t") + "\n"
    s += rows("REL_SLOW", release(8.0, 0.093), "uint32_t") + "\n"
    s += ("/* round(65536 / (1 + m/256)), m=0..256: reciprocal mantissas for PolyBLEP.\n"
          " * The last entry is the interpolation endpoint. No division in the audio ISR. */\n")
    s += "/* Actual times in milliseconds, for the panel: no division on the chip. */\n"
    s += rows("REL_FAST_MS", release_ms(0.054, 0.0024), "uint16_t") + "\n"
    s += rows("REL_SLOW_MS", release_ms(8.0, 0.093), "uint16_t") + "\n"
    s += rows("ATK_MS", attack_ms(), "uint16_t") + "\n"
    r = [round(65536 / (1 + m / 256)) for m in range(257)]
    s += "static const uint32_t BLEP_RECIP[257] = {\n"
    for i in range(0, 257, 8):
        s += "    " + ", ".join(f"{v}u" for v in r[i:i + 8]) + ",\n"
    return s + "};\n"


if __name__ == "__main__":
    import sys
    text = make()
    if "--check" in sys.argv:
        raise SystemExit(0 if OUT.exists() and OUT.read_text() == text else "artihive_tables.h is stale; run tools/gen_dsp_tables.py")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(OUT)
