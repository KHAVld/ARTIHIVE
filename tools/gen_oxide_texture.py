#!/usr/bin/env python3
"""Generate the approved strong OXIDE patina as a fixed 2-bit 240x240 map."""
from pathlib import Path
import random
from PIL import Image, ImageDraw, ImageFilter

W = H = 240
random.seed(11408)
mask = Image.new("L", (W, H), 0)
d = ImageDraw.Draw(mask)
for _ in range(35):
    x = random.randint(-20, 260); y = random.randint(-15, 178)
    rx = random.randint(5, 30); ry = random.randint(3, 18)
    d.ellipse((x-rx, y-ry, x+rx, y+ry), fill=random.randint(35, 100))
    if random.random() < .68:
        w = random.randint(1, 4); ln = random.randint(10, 55)
        d.rounded_rectangle((x-w, y, x+w, y+ln), radius=w, fill=random.randint(28, 78))
for box, value in [((-35,-15,65,82),105), ((168,-35,270,52),90),
                   ((184,84,275,184),82), ((-42,112,43,208),78),
                   ((72,38,166,95),52)]:
    d.ellipse(box, fill=value)
mask = mask.filter(ImageFilter.GaussianBlur(3.2))
mp = mask.load()
levels = [0] * (W * H)
for y in range(H):
    for x in range(W):
        q = min(.68, mp[x, y] / 255 * 1.75)
        # Four reproducible oxide strengths. Sparse hard flakes reproduce the approved preview.
        grain = (x * 11 + y * 23 + x * y) & 63
        if q < .055:
            lv = 0
        elif q < .20:
            lv = 1 if grain < 38 else 0
        elif q < .39:
            lv = 2 if grain < 52 else 1
        else:
            lv = 3 if grain < 54 else 2
        if ((x * 37 + y * 71) & 255) < int(q * 19):
            lv = 3
        levels[y * W + x] = lv
packed = bytearray((W * H + 3) // 4)
for i, lv in enumerate(levels):
    packed[i >> 2] |= lv << ((i & 3) * 2)
out = Path(__file__).resolve().parent.parent / "firmware/gen/oxide_texture.h"
rows = []
for i in range(0, len(packed), 24):
    rows.append("    " + ",".join(f"0x{x:02x}" for x in packed[i:i+24]) + ",")
out.write_text("/* generated by tools/gen_oxide_texture.py; approved OXIDE patina, 2 bits/pixel */\n"
               "static const uint8_t OXIDE_TEX[14400] = {\n" + "\n".join(rows) + "\n};\n")
print(out, len(packed), "bytes")
